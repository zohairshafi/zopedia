#!/bin/bash
# Archive, export, and optionally upload the native iOS app.
#
#   ./scripts/archive-testflight.sh            # archive + export
#   ./scripts/archive-testflight.sh --upload   # also upload to TestFlight
#
# Upload needs ASC_KEY_ID, ASC_ISSUER_ID, and an App Store Connect API key at
# ~/.appstoreconnect/private_keys/AuthKey_<ASC_KEY_ID>.p8 (or ASC_KEY_PATH).
#
# Exporting needs an Apple ID signed into Xcode (Settings > Accounts) with the
# team 6NHRH72J3M, or the API key above; automatic signing creates the App Store
# profile. Without either, the archive succeeds but export fails with
# "No Accounts" / "No profiles".
set -euo pipefail

# Resolve tools before the PATH reset below.
XCODEGEN="$(command -v xcodegen || true)"

# conda exports a non-Apple linker via LD and a macOS-version SDKROOT. Both
# break xcodebuild's link step, so strip them before doing anything else.
unset LD SDKROOT CC CXX CPP CFLAGS CXXFLAGS LDFLAGS CONDA_PREFIX CONDA_DEFAULT_ENV 2>/dev/null || true
export PATH="/usr/bin:/bin:/usr/sbin:/sbin:/Applications/Xcode.app/Contents/Developer/usr/bin"
export DEVELOPER_DIR=/Applications/Xcode.app/Contents/Developer

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
IOS_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
ROOT="$(cd "$IOS_DIR/.." && pwd)"
cd "$IOS_DIR"

VERSION="$(
  /usr/bin/python3 - "$ROOT/packaging/__version__.py" <<'PY'
import pathlib
import re
import sys

text = pathlib.Path(sys.argv[1]).read_text()
match = re.search(r'__version__\s*=\s*"([0-9]+\.[0-9]+\.[0-9]+)"', text)
if not match:
    raise SystemExit("packaging/__version__.py has no x.y.z __version__")
print(match.group(1))
PY
)"
BUILD="${ZOPEDIA_BUILD_NUMBER:-$(git -C "$ROOT" rev-list --count HEAD)}"

cat > Config/Version.xcconfig <<EOF
// Regenerated by scripts/archive-testflight.sh.
ZOPEDIA_MARKETING_VERSION = $VERSION
ZOPEDIA_BUILD_NUMBER = $BUILD
MARKETING_VERSION = \$(ZOPEDIA_MARKETING_VERSION)
CURRENT_PROJECT_VERSION = \$(ZOPEDIA_BUILD_NUMBER)
EOF

if [ -z "$XCODEGEN" ]; then
  echo "xcodegen is required: brew install xcodegen" >&2
  exit 1
fi
"$XCODEGEN" generate

rm -rf build/Zopedia.xcarchive build/export
mkdir -p build

echo "== archiving $VERSION ($BUILD) =="
xcodebuild \
  -project Zopedia.xcodeproj \
  -scheme Zopedia \
  -configuration Release \
  -destination 'generic/platform=iOS' \
  -archivePath build/Zopedia.xcarchive \
  -allowProvisioningUpdates \
  MARKETING_VERSION="$VERSION" \
  CURRENT_PROJECT_VERSION="$BUILD" \
  archive

echo "== exporting =="
xcodebuild -exportArchive \
  -archivePath build/Zopedia.xcarchive \
  -exportOptionsPlist Config/ExportOptions.plist \
  -exportPath build/export \
  -allowProvisioningUpdates

"$SCRIPT_DIR/verify-release.sh" build/export/Zopedia.ipa "$VERSION"

echo "archive: build/Zopedia.xcarchive"
echo "ipa:     build/export/Zopedia.ipa"
echo "version: $VERSION ($BUILD)"

if [ "${1:-}" = "--upload" ]; then
  : "${ASC_KEY_ID:?Set ASC_KEY_ID to the App Store Connect API key id}"
  : "${ASC_ISSUER_ID:?Set ASC_ISSUER_ID to the App Store Connect issuer id}"
  KEY_PATH="${ASC_KEY_PATH:-$HOME/.appstoreconnect/private_keys/AuthKey_${ASC_KEY_ID}.p8}"
  if [ ! -f "$KEY_PATH" ]; then
    echo "missing App Store Connect key at $KEY_PATH" >&2
    exit 1
  fi

  echo "== uploading to TestFlight =="
  xcrun altool --upload-app \
    --type ios \
    --file build/export/Zopedia.ipa \
    --apiKey "$ASC_KEY_ID" \
    --apiIssuer "$ASC_ISSUER_ID"
fi
